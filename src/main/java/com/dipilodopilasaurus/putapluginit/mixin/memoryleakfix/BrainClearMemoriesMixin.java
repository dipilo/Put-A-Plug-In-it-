package com.dipilodopilasaurus.putapluginit.mixin.memoryleakfix;

import net.minecraft.world.entity.ai.Brain;
import net.minecraft.world.entity.ai.memory.MemoryModuleType;
import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;

import java.util.Map;
import java.util.Optional;

@Mixin(Brain.class)
public abstract class BrainClearMemoriesMixin implements ExtendBrain {
	@Shadow
	@Final
	private Map<MemoryModuleType<?>, Optional<?>> memories;

	@Shadow
	public abstract void setMemory(MemoryModuleType<?> memoryModuleType, Optional<?> optional);

	@Override
	public void papiClearMemories() {
		this.memories.keySet().forEach(module -> this.setMemory(module, Optional.empty()));
	}
}
